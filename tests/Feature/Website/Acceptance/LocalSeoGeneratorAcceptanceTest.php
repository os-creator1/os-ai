/**
 * Local SEO generator acceptance: a FRESH Spokane-style photo booth site (seven service areas, as on the live Transparent Photo
 * Booths benchmark) is generated by the real guided generator, published to a customer domain and read over real HTTP.
 * It proves the structural defects of the benchmark do not recur in a newly generated site: no name-swapped city pages, a
 * visible areas list, intent-led titles, contextual links, correct crawl files, redirects for old spellings, truthful structured
 * data, a blog that appears only once an article is live, tenant isolation and immutable published revisions.
 */
class LocalSeoGeneratorAcceptanceTest extends TestCase
{
    use CreatesWebsiteFixtures;
    use DrivesGuidedWizard;
    use RefreshDatabase;

    private const DOMAIN = 'spokane-booths.test';

    private const AREAS = ['Spokane, WA', 'Spokane Valley, WA', 'Liberty Lake, WA', 'Cheney, WA', 'Airway Heights, WA', "Coeur d'Alene, ID", 'Post Falls, ID'];

    protected function setUp(): void
    {
        parent::setUp();
        $this->seedGuidedWizard();

        $ai = \Mockery::mock(WebsiteAiGenerationClient::class);
        $ai->shouldNotReceive('complete');
        $ai->shouldReceive('lastCallWasBudgetExhausted')->andReturn(false);
        $ai->shouldReceive('lastRefusalReason')->andReturn(null);
        $this->app->instance(WebsiteAiGenerationClient::class, $ai);
    }

    private function publishedSite(): Website
    {
        $this->tenant(['name' => 'Glow Booths'], ['city' => 'Spokane', 'region' => 'WA']);
        $this->completeGuidedSetup([
            'base_location' => fn () => $this->continueStep('base_location', ['value' => ['city' => 'Spokane', 'region' => 'WA', 'country_code' => 'US']]),
            'service_area_cities' => fn () => $this->continueStep('service_area_cities', ['value' => self::AREAS]),
        ]);
        $this->uploadGalleryPhotos(6);
        Website::where('business_id', $this->business->id)->update(['template_key' => 'photo_booth_modern']);

        $this->post($this->url('generate'), ['answers_revision' => $this->wizardSession()->answers_revision])->assertRedirect();
        $website = Website::where('business_id', $this->business->id)->firstOrFail();

        app(WebsiteSearchVisibility::class)->release($website);
        app(WebsitePublisher::class)->publish($website->fresh(), $this->platformAdminId());
        $website->domains()->create(['domain' => self::DOMAIN, 'is_primary' => true, 'status' => WebsiteDomainStatus::Active, 'verification_token' => 't', 'verified_at' => now(), 'activated_at' => now()]);

        return $website->fresh();
    }

    private function html(string $path): string
    {
        return $this->get('http://' . self::DOMAIN . $path)->assertOk()->getContent();
    }

    /** @return array<int, string> the hrefs inside <main> */
    private function mainLinks(string $html): array
    {
        preg_match('#<main.*?</main>#s', $html, $main);
        preg_match_all('#<a [^>]*href="([^"]+)"#', $main[0] ?? '', $links);

        return $links[1];
    }

    private function jsonLd(string $html, string $type): ?array
    {
        preg_match_all('#<script type="application/ld\+json">(.*?)</script>#s', $html, $matches);
        foreach ($matches[1] as $json) {
            $decoded = json_decode($json, true);
            foreach (isset($decoded['@graph']) ? $decoded['@graph'] : [$decoded] as $item) {
                if (($item['@type'] ?? null) === $type) {
                    return $item;
                }
            }
        }

        return null;
    }

    public function test_a_freshly_generated_site_has_the_architecture_the_benchmark_lacked(): void
    {
        $website = $this->publishedSite();
        $pages = $website->pages()->get();

        // Architecture: no name-swapped city pages; every page records its role; every service page is a described booth.
        $this->assertSame(0, $pages->filter(fn ($p) => str_starts_with((string) $p->slug, 'serving-'))->count(), 'Seven bare city names earn no pages of their own.');
        $this->assertSame([], $pages->filter(fn ($p) => $p->page_role === null)->pluck('slug')->all());
        $this->assertSame(2, $pages->where('page_role', 'service')->count());

        // Home: the areas list names all seven places, in the owner's order, as visible copy.
        $home = $this->html('/');
        $this->assertStringContainsString('Areas we serve', $home);
        foreach (['Spokane', 'Spokane Valley', 'Liberty Lake', 'Cheney', 'Airway Heights', "Coeur d'Alene", 'Post Falls'] as $place) {
            $this->assertStringContainsString(htmlspecialchars($place, ENT_QUOTES), $home, "{$place} is listed on the home page.");
        }

        // Metadata: intent first, brand once, unique descriptions that end like sentences.
        preg_match('#<title>(.*?)</title>#s', $home, $title);
        $this->assertSame('Photo Booth Rentals in Spokane | Glow Booths', html_entity_decode($title[1]));
        $descriptions = [];
        foreach ($pages as $page) {
            $html = $this->html($page->is_home ? '/' : '/' . $page->slug);
            preg_match('#<meta name="description" content="([^"]*)"#', $html, $d);
            $description = html_entity_decode($d[1] ?? '');
            $this->assertMatchesRegularExpression('/[.!?]$/', $description, "{$page->slug}: finished description");
            $this->assertSame(1, preg_match_all('#<h1[ >]#', $html), "{$page->slug}: exactly one H1");
            $this->assertStringContainsString('<link rel="canonical" href="https://' . self::DOMAIN . ($page->is_home ? '/' : '/' . $page->slug) . '">', $html);
            $descriptions[$description] = true;
        }
        $this->assertCount($pages->count(), $descriptions, 'Every description is unique.');

        // Contextual links: the home page and each booth page lead to the booth pages inside their own content.
        $servicePages = $pages->where('page_role', 'service')->values();
        foreach ($servicePages as $service) {
            $this->assertContains('https://' . self::DOMAIN . '/' . $service->slug, $this->mainLinks($home), 'The home page links to ' . $service->slug . ' from its content.');
            $other = $servicePages->firstWhere('slug', '!=', $service->slug);
            $this->assertContains('https://' . self::DOMAIN . '/' . $other->slug, $this->mainLinks($this->html('/' . $service->slug)), $service->slug . ' links on to the other booth.');
        }

        // Structured data: one stable entity, confirmed coverage the site names, nothing invented.
        $business = $this->jsonLd($home, 'LocalBusiness');
        $this->assertSame('https://' . self::DOMAIN . '/#business', $business['@id']);
        $this->assertSame('Glow Booths', $business['name']);
        $this->assertContains('Cheney', array_column($business['areaServed'], 'name'));
        $this->assertArrayNotHasKey('aggregateRating', $business);
        $this->assertSame('https://' . self::DOMAIN . '/#business', $this->jsonLd($this->html('/' . $servicePages[0]->slug), 'LocalBusiness')['@id']);
    }

    public function test_crawl_files_redirects_and_missing_pages_behave(): void
    {
        $website = $this->publishedSite();

        $robots = $this->get('http://' . self::DOMAIN . '/robots.txt')->assertOk();
        $this->assertStringContainsString('Sitemap: https://' . self::DOMAIN . '/sitemap.xml', $robots->getContent());
        $this->assertStringNotContainsString('Disallow: /', str_replace('Disallow:' . "\n", '', $robots->getContent()), 'Nothing is blocked.');

        $sitemap = $this->get('http://' . self::DOMAIN . '/sitemap.xml')->assertOk();
        $sitemap->assertHeader('Content-Type', 'application/xml; charset=UTF-8');
        preg_match_all('#<loc>(.*?)</loc>#', $sitemap->getContent(), $locs);
        $this->assertCount($website->pages()->count(), $locs[1], 'Every published, indexable page and nothing else.');
        foreach ($locs[1] as $loc) {
            $this->assertStringStartsWith('https://' . self::DOMAIN . '/', $loc);
            $this->assertStringNotContainsString('getmotiongrove', $loc);
        }
        $this->assertNotContains('https://' . self::DOMAIN . '/blog', $locs[1], 'No blog URL until an article is live.');

        // An old one-word spelling and a different case reach the real page by a permanent redirect, never a 404 (the trailing-slash 301 is covered by the custom-domain rendering tests).
        $service = $website->pages()->where('page_role', 'service')->firstOrFail();
        $oneWord = str_replace('-', '', $service->slug);
        $this->assertSame(301, $this->get('http://' . self::DOMAIN . '/' . $oneWord)->getStatusCode(), "one-word spelling {$oneWord}");
        $this->get('http://' . self::DOMAIN . '/' . $oneWord)->assertRedirect('https://' . self::DOMAIN . '/' . $service->slug);
        $this->assertSame(301, $this->get('http://' . self::DOMAIN . '/' . strtoupper($service->slug))->getStatusCode(), 'upper-case spelling');

        // A page that never existed is a real 404, noindex.
        $this->get('http://' . self::DOMAIN . '/not-a-page-here')->assertNotFound()->assertHeader('X-Robots-Tag', 'noindex, follow');
    }

    public function test_the_blog_appears_only_after_the_first_article_and_links_to_the_page_it_supports(): void
    {
        $website = $this->publishedSite();
        $this->get('http://' . self::DOMAIN . '/blog')->assertNotFound();
        $this->assertStringNotContainsString('/blog"', $this->html('/'), 'No empty blog link beforehand.');

        $service = $website->pages()->where('page_role', 'service')->firstOrFail();
        $publishedUid = collect(WebsiteRevision::find($website->published_revision_id)->snapshot['pages'])->firstWhere('slug', $service->slug)['uid'];
        $body = str_repeat('A photo booth needs a flat, dry corner with a power outlet within reach, about ten feet of floor space and a clear way in for the attendant. Tell your venue the date early so load-in is agreed. ', 8)
            . "\n\nIf you are comparing options, start with the [booth we recommend most](page:{$publishedUid}).";
        $article = app(ArticleManager::class)->create((int) $this->business->customer_id, $this->business, [
            'title' => 'How Much Space Does a Photo Booth Need?', 'excerpt' => 'The floor space, power and access a photo booth needs.',
            'body' => $body, 'meta_description' => 'The floor space, power and access a photo booth needs at your venue, with a few planning tips for your date.',
            'primary_topic' => 'how much space does a photo booth need', 'search_intent' => 'planning', 'supports_page_uid' => $publishedUid,
        ]);
        app(ArticleManager::class)->publish((int) $this->business->customer_id, $this->business, $article);

        $post = $this->get('http://' . self::DOMAIN . '/blog/' . $article->slug)->assertOk();
        $html = $post->getContent();
        $this->assertStringContainsString('<link rel="canonical" href="https://' . self::DOMAIN . '/blog/' . $article->slug . '">', $html);
        $this->assertStringContainsString('href="https://' . self::DOMAIN . '/' . $service->slug . '"', $html, 'The article links to the page it supports.');
        $this->assertNotNull($this->jsonLd($html, 'BlogPosting'));
        $this->assertStringContainsString('href="https://' . self::DOMAIN . '/blog"', $this->html('/'), 'The Blog entry appears once an article is live.');
        $this->assertStringContainsString('/blog/' . $article->slug, $this->get('http://' . self::DOMAIN . '/sitemap.xml')->getContent());
        $this->assertStringContainsString('Helpful guides', $this->html('/' . $service->slug), 'The supported page lists the article.');
    }

    public function test_published_revisions_are_immutable_and_tenants_are_isolated(): void
    {
        $website = $this->publishedSite();
        $first = WebsiteRevision::find($website->published_revision_id);
        $frozen = json_encode($first->snapshot);

        // Edit the draft and publish again: the earlier revision is untouched.
        $website->pages()->where('is_home', true)->update(['seo_title' => 'A changed title']);
        app(WebsitePublisher::class)->publish($website->fresh(), $this->platformAdminId());
        $this->assertSame($frozen, json_encode(WebsiteRevision::find($first->id)->snapshot));

        // A second business on its own domain never leaks into this one.
        [, $other] = $this->entitledTenant(['name' => 'Rival Booths']);
        $otherSite = $this->createWebsite($other);
        $this->homePage($otherSite);
        app(WebsitePublisher::class)->publish($otherSite, $this->platformAdminId());
        $otherSite->domains()->create(['domain' => 'rival-booths.test', 'is_primary' => true, 'status' => WebsiteDomainStatus::Active, 'verification_token' => 't', 'verified_at' => now(), 'activated_at' => now()]);

        $mine = $this->get('http://' . self::DOMAIN . '/sitemap.xml')->getContent() . $this->html('/');
        $theirs = $this->get('http://rival-booths.test/sitemap.xml')->getContent() . $this->get('http://rival-booths.test/')->getContent();
        $this->assertStringNotContainsString('Rival Booths', $mine);
        $this->assertStringNotContainsString('Glow Booths', $theirs);
        $this->assertStringNotContainsString(self::DOMAIN, $theirs);
    }
}
