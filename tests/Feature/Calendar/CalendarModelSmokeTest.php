<?php

namespace Tests\Feature\Calendar;

use App\Enums\Calendar\AppointmentStatus;
use App\Enums\Calendar\ExternalCalendarConnectionState;
use App\Enums\Calendar\ExternalCalendarProvider;
use App\Models\Appointment;
use App\Models\BookingContactIdentityLock;
use App\Models\BookingType;
use App\Models\BookingTypeRoundRobinState;
use App\Models\ExternalCalendarBusyBlock;
use App\Models\ExternalCalendarConnection;
use App\Models\StaffAvailabilityRule;
use App\Models\StaffBookingLock;
use App\Models\StaffTimeOff;
